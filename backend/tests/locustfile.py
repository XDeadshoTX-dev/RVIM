import random
import string

from locust import HttpUser, task, between


class TodoUser(HttpUser):
    wait_time = between(1, 3)

    def on_start(self):
        email = f"loadtest_{''.join(random.choices(string.ascii_lowercase, k=10))}@test.com"
        self.client.post("/api/auth/sign-up", json={
            "firstName": "Load",
            "lastName": "Test",
            "email": email,
            "password": "TestPass123"
        })
        resp = self.client.post("/api/auth/log-in", json={
            "email": email,
            "password": "TestPass123"
        })
        self.list_id = None

    @task(5)
    def get_lists(self):
        self.client.get("/api/todo/lists")

    @task(2)
    def create_list(self):
        resp = self.client.post("/api/todo/lists/create", json={
            "title": f"Load Test List {random.randint(1, 10000)}",
            "description": "Generated by locust"
        })
        if resp.status_code == 201:
            self.list_id = resp.json()["data"]["id"]

    @task(1)
    def create_item(self):
        if not self.list_id:
            resp = self.client.post("/api/todo/lists/create", json={"title": "Seed list"})
            if resp.status_code == 201:
                self.list_id = resp.json()["data"]["id"]
        if self.list_id:
            self.client.post("/api/todo/items/create", json={
                "listId": self.list_id,
                "title": f"Load Test Item {random.randint(1, 10000)}"
            })

    @task(1)
    def health_check(self):
        self.client.get("/about/")